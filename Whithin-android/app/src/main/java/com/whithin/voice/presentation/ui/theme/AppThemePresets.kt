package com.whithin.voice.presentation.ui.theme

import androidx.compose.material3.ColorScheme
import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.ui.graphics.Color

data class AppThemePreset(
    val id: String,
    val name: String,
    val description: String,
    val background: Color,
    val surface: Color,
    val surfaceVariant: Color,
    val primary: Color,
    val onPrimary: Color,
    val onBackground: Color,
    val onSurface: Color,
    val onSurfaceVariant: Color,
    val serverListBackground: Color,
    val isLight: Boolean = false,
) {
    fun toColorScheme(): ColorScheme {
        val outlineColor = onSurfaceVariant.copy(alpha = if (isLight) 0.42f else 0.34f)
        val outlineVariantColor = onSurfaceVariant.copy(alpha = if (isLight) 0.24f else 0.20f)
        val scrimColor = Color.Black.copy(alpha = if (isLight) 0.4f else 0.55f)

        return if (isLight) {
            lightColorScheme(
                primary = primary,
                onPrimary = onPrimary,
                background = background,
                onBackground = onBackground,
                surface = surface,
                onSurface = onSurface,
                surfaceVariant = surfaceVariant,
                onSurfaceVariant = onSurfaceVariant,
                secondary = primary,
                onSecondary = onPrimary,
                outline = outlineColor,
                outlineVariant = outlineVariantColor,
                scrim = scrimColor,
            )
        } else {
            darkColorScheme(
                primary = primary,
                onPrimary = onPrimary,
                background = background,
                onBackground = onBackground,
                surface = surface,
                onSurface = onSurface,
                surfaceVariant = surfaceVariant,
                onSurfaceVariant = onSurfaceVariant,
                secondary = StaticDiscordSuccess,
                onSecondary = Color.White,
                error = StaticDiscordError,
                onError = Color.White,
                outline = outlineColor,
                outlineVariant = outlineVariantColor,
                scrim = scrimColor,
            )
        }
    }
}

